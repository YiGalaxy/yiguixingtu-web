import { describe, it, expect } from 'vitest'
import { formatFileSize } from '~/utils/fileSize'

// =====================================================================
// 文件大小的显示规则（app/utils/fileSize.ts）
//
// 【为什么一个只有 8 行的换算函数要单独一份测试】
//   附件列表里那个"多大"的数字全是它算出来的（后台弹窗的附件清单 + 文章页的附件列表）。
//   它写错的表现**一条都不是报错**，而是页面上一个看起来像真的的错数字：
//     · 进制用 1000 而不是 1024 → 界面上写着"单个附件不超过 100MB"，
//       用户传一个 100MB 的文件被拒，去"文件属性"里看却是 95.4 MB ——
//       这种对不上最容易让人以为系统有 bug（而"系统有 bug"是最难解释给用户听的一句话）
//     · 换档的那一个字节算错（1024 显示成 "1024 B"）→ 数字没错，但没人读得懂
//     · 非法输入没兜住 → 直接在页面上印一个 `NaN B`，或者留一个空白单元格
//   所以下面按"四个量级 + 换档边界 + 非法输入"三组，把每一处都钉住。
//
// 【为什么放在纯函数这一层】它没有依赖、不需要挂载任何组件，喂一个数字就能断言 ——
//   组件层那边只断言"这个值真的渲染到了那一格里"（见 test/articleAttachments.nuxt.spec.ts）。
// =====================================================================

describe('formatFileSize —— 文件大小的显示', () => {
  // ---------------------------------------------------------------
  // 一、四个量级（B / KB / MB / GB）各自的样子
  // ---------------------------------------------------------------

  it('小于 1KB_should按字节显示（整数、带 B）', () => {
    expect(formatFileSize(0)).toBe('0 B')
    expect(formatFileSize(1)).toBe('1 B')
    expect(formatFileSize(512)).toBe('512 B')
    // 1023 是 B 这一档的最后一个值（再多一个字节就该换档了）
    expect(formatFileSize(1023)).toBe('1023 B')
  })

  it('1024 字节_should显示成 1 KB（换档的那一个字节不能算错）', () => {
    // 【为什么单独拎出来一条】1023 → "1023 B"、1024 → "1 KB"。
    //   边界写成 `<= 1024` 的话，1024 会显示成 "1024 B" ——
    //   功能上没坏、也没有任何工具会报错，只是那一行看起来像没算过。
    expect(formatFileSize(1024)).toBe('1 KB')
  })

  it('KB 档_should四舍五入到整数（KB 之后的小数没有意义，只会把那一行撑长）', () => {
    expect(formatFileSize(1536)).toBe('2 KB')            // 1.5 KB 进位
    expect(formatFileSize(1024 * 1023)).toBe('1023 KB')  // KB 这一档的最后一个值
  })

  it('⚠️ 差一个字节不到 1MB_should显示成「1024 KB」（四舍五入的取舍，记录现状）', () => {
    // 1048575 B = 1023.999 KB，"先按档位取整、再决定要不要换档"的结果是 1024 KB。
    // 这不是算错（真值确实在 KB 这一档里），但它是本函数唯一一处"看起来像溢出了"的输出。
    // 写在这里是为了：哪天有人想让这一格显示成 1.0 MB，改的应该是函数的取整时机，
    // 而且改完之后这一条会红、提醒他把期望值一起改对（而不是悄悄改掉）。
    expect(formatFileSize(1024 * 1024 - 1)).toBe('1024 KB')
  })

  it('MB 档_should保留一位小数（一位足够：那一行还要留位置给文件名）', () => {
    expect(formatFileSize(1024 * 1024)).toBe('1.0 MB')
    expect(formatFileSize(1.5 * 1024 * 1024)).toBe('1.5 MB')
    // 附件上限就是 100MB：用户看到自己那个文件刚好是 "100.0 MB" 时不该被拦下
    expect(formatFileSize(100 * 1024 * 1024)).toBe('100.0 MB')
  })

  it('GB 档_should保留两位小数（1.25 GB 这类值必须体现得出来）', () => {
    expect(formatFileSize(1024 ** 3)).toBe('1.00 GB')
    expect(formatFileSize(1.5 * 1024 ** 3)).toBe('1.50 GB')
    expect(formatFileSize(2.25 * 1024 ** 3)).toBe('2.25 GB')
  })

  it('按 1024 进制而不是 1000（用 1000 的话会与后端的上限文案当场对不上）', () => {
    // 【这条用例是"进制"那件事的可测版本】100MB 这个数字出现了两次：
    //   一次在后端/前端的规则里（100 * 1024 * 1024），一次在给用户看的提示里（"100MB"）。
    // 下面的输入按 1000 进制算正好是 100 MB，按 1024 算是 95.4 MB ——
    //  把 95.4 显示出来，用户才会明白"为什么我 100MB 的文件被拒了"。
    expect(formatFileSize(100 * 1000 * 1000)).toBe('95.4 MB')
  })

  // ---------------------------------------------------------------
  // 二、非法输入：必须是「—」
  //
  // 【为什么必须是「—」而不是空串】空白单元格会让人以为"页面没加载出来"、
  //   以为是漏了一行；「—」在本项目里是统一的"这一格没有值"符号
  //   （与 formatDateTime 一致），它明确地表达"这一格本来就没有值"。
  // ---------------------------------------------------------------

  it('负数_should给「—」（字节数不可能是负的，那说明这个值不是大小）', () => {
    expect(formatFileSize(-1)).toBe('—')
    expect(formatFileSize(-1024 * 1024)).toBe('—')
  })

  it('NaN 与非数字内容_should给「—」（绝不能印出 `NaN B`）', () => {
    for (const bad of [NaN, 'abc', undefined, {}, Infinity, -Infinity]) {
      expect(formatFileSize(bad)).toBe('—')
    }
  })

  it('字符串数字_should照常换算（接口把大小回成字符串时不该显示「—」）', () => {
    // 后端正常给的是数字，但 JSON 里 `"size": "2048"` 这种形状出现过不止一次
    // （Long 在前端超过安全整数、或者某个中间层把数字转成了字符串）。
    // 这种情况下的正确反应是"照常显示"，而不是把用户明明看得到的大小变成「—」。
    expect(formatFileSize('2048')).toBe('2 KB')
    expect(formatFileSize('1048576')).toBe('1.0 MB')
  })

  it('null / 空串 / 空数组_should给「—」（它们是"没有值"，不是"0 字节"）', () => {
    // 【这一条原来是"记录现状"的】函数的上一版只判 `Number.isFinite(Number(x))`，
    // 而 `Number(null) === 0`、`Number('') === 0`、`Number([]) === 0` —— 于是"没有值"
    // 被显示成 `0 B`。而 0 字节的文件在上传时就被拦下了（useUpload 里的"不能上传空文件"），
    // 所以 `0 B` 这个显示结果本身就是错的：用户看到"一个 0 字节的文件"只会困惑。
    // 现在函数只接受「数字」与「非空数字字符串」，这三种输入都落到「—」。
    expect(formatFileSize(null)).toBe('—')
    expect(formatFileSize('')).toBe('—')
    expect(formatFileSize([])).toBe('—')
  })

  // ---------------------------------------------------------------
  // 三、这条规则最要紧的一句：返回值永远能直接放进单元格里
  // ---------------------------------------------------------------

  it('对任何输入_should都返回一个非空、且不含 NaN 的字符串（调用方直接就往模板里插）', () => {
    // 【为什么单列一条"总体性质"】上面是一条条列的边界，
    //   而调用方（附件列表）是直接把返回值插进 {{ }} 的：
    //   一旦哪条路径漏出 `undefined` / `NaN B` / 空串，
    //   页面上就会出现"这一格什么都没写"，而且**不会报错**。
    //   这里用一批混合输入把这条性质钉住（含上面每一组的代表）。
    const samples = [0, 1, 512, 1023, 1024, 1536, 1024 ** 2, 1.5 * 1024 ** 2, 1024 ** 3, -1, NaN, '', null, undefined, 'abc', '2048', {}]
    for (const sample of samples) {
      const text = formatFileSize(sample)
      expect(typeof text).toBe('string')
      expect(text.length).toBeGreaterThan(0)
      expect(text).not.toContain('NaN')
      // 「—」或者"数字 + 单位"这两种形状之一，不该有第三种
      expect(text === '—' || /^\d+(\.\d+)? (B|KB|MB|GB)$/.test(text)).toBe(true)
    }
  })
})
