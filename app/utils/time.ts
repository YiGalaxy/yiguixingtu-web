/**
 * 时间显示的唯一规则（后台四张表格 + 概览的「最近文章」都用它）。
 *
 * 【为什么抽成纯函数】拆后台组件之前，这一行代码是 admin.vue 里的一个 `fmtTime`，
 * 拆完之后概览 / 文章 / 用户 / 评论四个面板都要用。四个面板各抄一份的话，
 * 以后想统一改成"相对时间"就得改四处，而且漏掉的那一处不会有任何报错 ——
 * 只是那一张表格的时间长得和别处不一样。
 *
 * 【为什么不用 dayjs / Intl.DateTimeFormat 格式化】
 *   后端给的是 `LocalDateTime` 序列化出来的字符串，**没有时区**（形如 `2026-09-10T05:03:19`）。
 *   交给 `new Date()` 会被按**浏览器本地时区**解析一次，再格式化回来就可能差一天
 *   （归档页那一节记过同一个坑）。所以这里只做**字符串层面的替换**：
 *   把日期与时间之间的 `T` 换成空格，再截掉毫秒/时区尾巴。
 *
 * @param {string|number|null|undefined} t 后端给的时间字符串
 * @returns {string} `2026-09-10 05:03:19`，拿不到时间时是「—」而不是空字符串
 *   （空白单元格会让人以为是"页面没加载出来"）
 */
export const formatDateTime = (t) => (t ? String(t).replace('T', ' ').slice(0, 19) : '—')
