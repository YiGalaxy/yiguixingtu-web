/**
 * =====================================================================
 * 访问上报：哪些路径要报、报什么
 *
 * 【为什么把这两条规则抽成纯函数】它们都是"一条判断"，而判断写错的表现是
 *   **统计里多一批或少一批数据** —— 页面完全正常，只是后台的数字不对。
 *   抽出来之后能直接断言规则本身，不用去挂载整个外壳、还要绕过路由守卫
 *   （后台未登录会被重定向，在组件测试里根本走不到 /admin 那一页）。
 * =====================================================================
 */

/**
 * 不上报的路径前缀。
 *
 * 【为什么后台不算访问】站长得天看后台（改文案、审评论），
 *   把那些算进去会把统计彻底带偏 —— 尤其是"访客身份"那张图
 *   会变成"管理员 100%"，而它对"有多少读者"这个问题毫无帮助。
 */
export const VISIT_EXCLUDED_PREFIXES = ['/admin']

/**
 * 这个路径要不要上报。
 *
 * @param path 路由的 path 部分（**不含查询串** —— 查询串里可能是搜索词之类的
 *             用户输入，不该进统计表；后端也会再洗一遍）
 * @returns 空值、非站内路径、以及后台路径都返回 false
 */
export const shouldReportVisit = (path) => {
  if (typeof path !== 'string') return false
  const trimmed = path.trim()
  // 必须以 / 开头：绝对地址、空串、乱七八糟的输入都不报
  // （后端也会把非站内路径丢掉，两道都在 —— 这道更早、也更省一次请求）
  if (!trimmed.startsWith('/')) return false
  // ⚠️ 匹配的是【路径段】，不是字符串前缀：'/administrator' 不该因为
  //    以 '/admin' 开头就被当成后台路径排除掉（那种过度排除的表现是
  //    "那个页面永远统计不到"，而且不会有任何报错）。
  //    所以判定条件是"恰好等于 /admin"或者"在 /admin/ 下面"。
  return !VISIT_EXCLUDED_PREFIXES.some(
    prefix => trimmed === prefix || trimmed.startsWith(`${prefix}/`),
  )
}
